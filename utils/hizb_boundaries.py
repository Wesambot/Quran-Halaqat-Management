# قائمة مرتبة من (رقم_السورة, رقم_الآية, رقم_الحزب) لتسهيل البحث الثنائي
_SORTED_BOUNDARIES = sorted(
    [(sura, ayah, hizb) for hizb, (sura, ayah) in HIZB_START_POINTS.items()]
)


def hizb_and_juz_for_ayah(sura_number: int, ayah_number: int) -> tuple:
    """
    يحسب رقم الحزب والجزء الدقيقين اللذين تقع فيهما آية معيّنة،
    عبر إيجاد آخر نقطة بداية حزب لا تتجاوز موقع هذه الآية في ترتيب المصحف.
    يُرجع (رقم_الجزء, رقم_الحزب).
    """
    current_hizb = 1
    for sura, ayah, hizb in _SORTED_BOUNDARIES:
        if (sura < sura_number) or (sura == sura_number and ayah <= ayah_number):
            current_hizb = hizb
        else:
            break
    juz = (current_hizb + 1) // 2
    return juz, current_hizb
